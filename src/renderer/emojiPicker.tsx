export function EmojiPicker(props: { onPick: (s: string) => void }) {
  const [cat, setCat] = useState(0);
  const [open, setOpen] = useState(false);

  return (
    <div className="emoji-picker-wrap">
      <button
        type="button"
        className="btn ghost tiny"
        onClick={() => setOpen((o) => !o)}
        title="Insert emoji / kaomoji"
      >
        {open ? '✕' : '😀'}
      </button>
      {open && (
        <div className="emoji-pop">
          <div className="emoji-tabs">
            {CATEGORIES.map((c, i) => (
              <button
                key={c.name}
                type="button"
                className={`emoji-tab ${i === cat ? 'on' : ''}`}
                onClick={() => setCat(i)}
              >
                {c.name}
              </button>
            ))}
          </div>
          <div className="emoji-grid">
            {CATEGORIES[cat]?.items.map((e, i) => (
              <button
                key={i}
                type="button"
                className="emoji-btn"
                onClick={() => props.onPick(e)}
                title={e}
              >
                {e}
              </button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
